/**
 * Generates the RNTester screen that renders the corpus on device.
 *
 * The screen is generated rather than hand-written for the same reason the
 * Safari page is: one corpus, three engines. A case edited in `cases.js` must
 * reach all of them or the comparison is between two different questions.
 *
 * What the screen publishes is `getBoundingClientRect()` — not
 * `measureInWindow` — because that is the API under test, and because it is
 * the only one that answers for an inline element, which is not a view.
 *
 * Usage: node gen-device-screen.js
 *
 * @noflow
 * @format
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const {cases, W, FS} = require('./cases.js');

const OUT = path.join(
  __dirname,
  '..',
  'packages',
  'rn-tester',
  'js',
  'examples',
  'TextConformance',
  'TextConformanceExample.js',
);

function serialize(value, indent) {
  return JSON.stringify(value, null, indent);
}

// Only the parts the screen needs: the tree and the container style. The
// assertions live on the node side, where the comparison happens.
const payload = cases.map(c => ({
  name: c.name,
  container: c.container ?? {},
  children: c.children ?? [],
}));

const file = `/*
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 *
 * This source code is licensed under the MIT license found in the
 * LICENSE file in the root directory of this source tree.
 *
 * @noflow
 * @format
 */

// GENERATED by text-conformance/gen-device-screen.js — do not edit by hand.
// Edit text-conformance/cases.js and regenerate.
//
// @noflow rather than strict-local: the corpus sets inheritable text
// properties (fontSize) on Views, which is exactly what this feature adds and
// exactly what ViewStyle does not yet describe, and it builds elements from
// data, so every tag is a computed string. Typing generated fixture data buys
// nothing the corpus does not already check by measurement.

import * as React from 'react';
import {ScrollView, Text, View} from 'react-native';

import '@react-native/expo-intrinsics-poc';

const W = ${W};
const FS = ${FS};

const CASES = ${serialize(payload, 1)};

/**
 * Renders one node of a case. A bare string stays a bare string — wrapping it
 * would turn anonymous text into an element and change the very thing several
 * cases are about.
 */
function renderNode(node, register, key) {
  if (typeof node === 'string') {
    return node;
  }
  const children = (node.children ?? []).map((child, i) =>
    renderNode(child, register, key + '.' + String(i)),
  );
  const props = {key};
  if (node.style != null) {
    props.style = node.style;
  }
  if (node.id != null) {
    const id = node.id;
    props.ref = instance => {
      register(id, instance);
    };
  }
  return React.createElement(node.tag, props, ...children);
}

function relativeRect(node, base) {
  if (node == null || base == null || typeof node.getBoundingClientRect !== 'function') {
    return null;
  }
  const r = node.getBoundingClientRect();
  const b = base.getBoundingClientRect();
  return {x: r.x - b.x, y: r.y - b.y, w: r.width, h: r.height};
}

function CaseView({item}) {
  const containerRef = React.useRef(null);
  const probes = React.useRef({}).current;

  const register = React.useCallback(
    (id, instance) => {
      probes[id] = instance;
    },
    [probes],
  );

  React.useEffect(() => {
    const publish = () => {
      const base = containerRef.current;
      if (base == null || typeof base.getBoundingClientRect !== 'function') {
        return;
      }
      const b = base.getBoundingClientRect();
      const measured = {
        container: {x: 0, y: 0, w: b.width, h: b.height},
        probes: {},
      };
      for (const id of Object.keys(probes)) {
        const rect = relativeRect(probes[id], base);
        if (rect != null) {
          measured.probes[id] = rect;
        }
      }
      const all = globalThis.__textConformance ?? {};
      all[item.name] = measured;
      globalThis.__textConformance = all;
    };
    // Twice: once when layout has settled, once more in case anything that
    // measures text asynchronously moved it after the first pass.
    const t1 = setTimeout(publish, 600);
    const t2 = setTimeout(publish, 2200);
    return () => {
      clearTimeout(t1);
      clearTimeout(t2);
    };
  }, [item, probes]);

  return (
    <View style={styles.caseWrapper}>
      <Text style={styles.caseName}>{item.name}</Text>
      <View
        ref={containerRef}
        style={[styles.container, {width: W, fontSize: FS}, item.container]}>
        {item.children.map((child, i) => renderNode(child, register, String(i)))}
      </View>
    </View>
  );
}

function TextConformanceScreen() {
  return (
    <ScrollView style={styles.scroll}>
      {CASES.map(item => (
        <CaseView key={item.name} item={item} />
      ))}
    </ScrollView>
  );
}

// The dashed outline lives on the WRAPPER, never on the measured container:
// probe rects are container-border-box relative, so a border there would shift
// every one of them by its width — and the web page draws its own with
// \`outline\`, which does not affect layout at all.
const styles = {
  scroll: {flex: 1, backgroundColor: '#f8fafc'},
  caseWrapper: {
    margin: 8,
    padding: 8,
    backgroundColor: '#ffffff',
    borderWidth: 1,
    borderColor: '#cbd5e1',
    borderStyle: 'dashed',
    alignSelf: 'flex-start',
  },
  caseName: {fontSize: 10, color: '#64748b', marginBottom: 4},
  // Black on white, like the oracle page: the corpus is about geometry, and a
  // theme that hides the text hides whether the geometry is describing it.
  container: {color: '#000000'},
};

export default {
  title: 'Text conformance',
  category: 'Basic',
  description:
    'Mixed inline / block / flex / inline-flex layout, pinned against real Safari. ' +
    'Publishes getBoundingClientRect() to globalThis.__textConformance for ' +
    'text-conformance/verify.js.',
  examples: [
    {
      title: 'Cases',
      render: () => <TextConformanceScreen />,
    },
  ],
};
`;

fs.mkdirSync(path.dirname(OUT), {recursive: true});
fs.writeFileSync(OUT, file);
console.log(`wrote ${OUT} (${cases.length} cases)`);
