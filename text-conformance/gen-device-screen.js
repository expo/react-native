'use strict';

/**
 * Generates the RNTester screen from `cases.js`.
 *
 * Generated rather than hand-written so that "the device rendered the same
 * markup as the browser" is guaranteed by construction. A hand-maintained
 * second copy of the corpus is the one thing that would make every number in
 * this harness untrustworthy: a mismatch would mean "the two trees differ"
 * rather than "the engines differ", and it would look identical.
 */

const {CASES} = require('./cases');
const fs = require('node:fs');
const path = require('node:path');

const SCREEN = path.join(
  __dirname,
  '../packages/rn-tester/js/examples/HTMLElements/HTMLConformanceExample.js',
);

const header = `/**
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 *
 * This source code is licensed under the MIT license found in the
 * LICENSE file in the root directory of this source tree.
 *
 * @noflow
 * @format
 */

'use strict';

/**
 * GENERATED by text-conformance/gen-device-screen.js — do not edit.
 *
 * Renders the conformance corpus and reports every measured box's rect,
 * relative to its own case root, to the harness on :8900. The browser side of
 * the same corpus is \`expected.json\`; \`verify.js\` compares them.
 *
 * Rects are reported relative to the case root so that a difference means a
 * layout difference. An absolute coordinate would also carry the screen's
 * padding, the scroll offset and the status bar, and a constant offset in all
 * of those looks exactly like a real bug.
 */

import {TERTIARY_COLOR} from './themed';
import * as React from 'react';
import {useCallback, useEffect, useRef, useState} from 'react';
import {ScrollView, Text, View} from 'react-native';

import '@react-native/expo-intrinsics-poc';

const REPORT_URL = 'http://localhost:8900/report';

const CORPUS = ${JSON.stringify(
  CASES.map(c => ({name: c.name, withText: c.withText === true, tree: c.tree})),
  null,
  2,
)};

/*
 * The corpus writes CSS lengths as strings ("40px") because that is what the
 * browser side needs. React Native takes numbers, so they are converted here
 * rather than stored twice — one corpus, two consumers.
 */
function toStyle(css) {
  const out = {};
  for (const [key, value] of Object.entries(css ?? {})) {
    if (typeof value === 'string' && /^-?\\d+(\\.\\d+)?px$/.test(value)) {
      out[key] = parseFloat(value);
    } else {
      out[key] = value;
    }
  }
  return out;
}

function render(node, refs, key) {
  if (typeof node === 'string') {
    return node;
  }
  const Tag = node.tag;
  const children = (node.children ?? []).map((child, i) =>
    render(child, refs, i),
  );
  const props = {key, style: toStyle(node.style)};
  if (node.m != null) {
    props.ref = instance => {
      if (instance != null) {
        refs.current[node.m] = instance;
      }
    };
  }
  return React.createElement(Tag, props, children.length ? children : undefined);
}

function Case({caseData, onMeasured}) {
  const refs = useRef({});

  const measure = useCallback(() => {
    const rootInstance = refs.current.root;
    if (rootInstance == null) {
      return;
    }
    const rootRect = rootInstance.getBoundingClientRect();
    const rects = {};
    for (const [m, instance] of Object.entries(refs.current)) {
      const r = instance?.getBoundingClientRect?.();
      if (r == null) {
        continue;
      }
      rects[m] = {
        x: Number((r.x - rootRect.x).toFixed(2)),
        y: Number((r.y - rootRect.y).toFixed(2)),
        width: Number(r.width.toFixed(2)),
        height: Number(r.height.toFixed(2)),
      };
    }
    onMeasured(caseData.name, rects);
  }, [caseData.name, onMeasured]);

  useEffect(() => {
    // One frame after mount: layout has to have run before a rect means
    // anything, and the images/controls in some cases resolve a frame later.
    const id = setTimeout(measure, 350);
    return () => clearTimeout(id);
  }, [measure]);

  return (
    <View style={{marginBottom: 24}}>
      <Text style={{fontSize: 10, color: TERTIARY_COLOR}}>{caseData.name}</Text>
      {render(caseData.tree, refs, caseData.name)}
    </View>
  );
}

function ConformanceScreen() {
  const results = useRef({});
  const [status, setStatus] = useState(\`measuring \${CORPUS.length} cases…\`);

  const onMeasured = useCallback((name, rects) => {
    results.current[name] = rects;
    if (Object.keys(results.current).length !== CORPUS.length) {
      return;
    }
    /*
     * The report is best-effort, and NOT reaching the harness is the normal
     * case.
     *
     * This screen is useful on its own — it is the corpus, rendered — and most
     * of the time nobody is running verify.js to receive the geometry. Showing
     * "report failed: Network request failed" then was wrong twice over: it put
     * an error on a screen that had done nothing wrong, and it trained the eye
     * to ignore the one line that would matter if a real failure appeared.
     */
    fetch(REPORT_URL, {
      method: 'POST',
      headers: {'Content-Type': 'application/json'},
      body: JSON.stringify(results.current),
    })
      .then(() => setStatus(\`reported \${CORPUS.length} cases to the harness\`))
      .catch(() =>
        setStatus(
          \`\${CORPUS.length} cases measured · harness not listening on :8900\`,
        ),
      );
  }, []);

  return (
    <ScrollView contentContainerStyle={{padding: 8}}>
      <Text style={{fontSize: 11, color: TERTIARY_COLOR, marginBottom: 8}}>
        {status}
      </Text>
      {CORPUS.map(c => (
        <Case key={c.name} caseData={c} onMeasured={onMeasured} />
      ))}
    </ScrollView>
  );
}

export default {
  title: 'HTML: conformance harness',
  category: 'UI',
  description:
    'Renders the text-conformance corpus and reports its geometry to the ' +
    'harness for comparison with real Safari.',
  examples: [
    {
      name: 'conformance',
      title: 'Corpus',
      render: () => <ConformanceScreen />,
    },
  ],
};
`;

fs.writeFileSync(SCREEN, header);

/*
 * The same corpus as data, for the Fantom verifier. Fantom runs the shared C++
 * layout without a device or a build, which turns a fix-and-check cycle from
 * ten minutes into one — the device remains the final word, but it is a poor
 * place to iterate.
 */
fs.writeFileSync(
  path.join(__dirname, 'corpus.json'),
  JSON.stringify(
    CASES.map(c => ({
      name: c.name,
      withText: c.withText === true,
      heightOnly: c.heightOnly === true,
      needsLineBreaking: c.needsLineBreaking === true,
      knownGap: c.knownGap ?? null,
      sameX: c.sameX ?? null,
      deltaX: c.deltaX ?? null,
      fontDependent: c.fontDependent ?? null,
      bounded: c.bounded ?? null,
      why: c.why,
      tree: c.tree,
    })),
    null,
    2,
  ),
);
console.log(
  `wrote ${path.relative(process.cwd(), SCREEN)} (${CASES.length} cases)`,
);
